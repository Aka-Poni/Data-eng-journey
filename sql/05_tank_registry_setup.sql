DROP TABLE IF EXISTS tank_registry; -- Delete table for clean startup. (OK here since it's a small table with test data generated by the script)
CREATE TABLE tank_registry (
    tank_id VARCHAR(15) PRIMARY KEY, -- Tank identifier. Stored as text, can't be null
    tank_name VARCHAR(50) DEFAULT NULL, -- Named after its process application; NULL means application not defined yet
    capacity_m3 DECIMAL(5,2) DEFAULT NULL -- Tank volume capacity. 999.99m³ is enough for our application
)
;

